import { BACKGROUND_CONTEXT as ctx } from "@earendil-works/chord/context";
import { createModels } from "@earendil-works/pi-ai/models";
import { fauxAssistantMessage, fauxProvider } from "@earendil-works/pi-ai/providers/faux";
import { createRegistry, Harness } from "@earendil-works/pi-durable";
import { openNodeSqliteStorage } from "@earendil-works/pi-durable/storage/sqlite/node";
const file = process.argv[2];
const faux = fauxProvider();
const models = createModels(); models.setProvider(faux.provider);
faux.setResponses([1,2,3,4,5,6].map((i) => fauxAssistantMessage(`answer ${i}`)));
const h = await Harness.open(await openNodeSqliteStorage(file), { models, registry: createRegistry() }, ctx);
const root = await h.root(ctx, { agent: { model: { provider: "faux", modelId: "faux-1" } } });
const s1 = await root.submit({ type: "input", content: "q1", requestId: "r1" }, ctx); await s1.wait(ctx);
const s2 = await root.submit({ type: "input", content: "q2", requestId: "r2" }, ctx); await s2.wait(ctx);
const again = await root.submit({ type: "input", content: "q1", requestId: "r1" }, ctx);
console.log("dedupe", again.id === s1.id);
const page = await root.entries({ order: "ascending" }, 50, undefined, ctx);
console.log(page.items.map((e) => `${e.id}:${e.kind}`).join(" "));
const firstAnswer = page.items.find((e) => e.kind === "pi.assistant")!;
const fork = await root.fork(firstAnswer.id, { ownership: { kind: "ownerless" } }, ctx);
await (await fork.submit({ type: "input", content: "branch q", requestId: "b1" }, ctx)).wait(ctx);
const fp = await fork.entries({ order: "ascending" }, 50, undefined, ctx);
console.log("fork", fp.items.map((e) => e.kind).join(","));
const rec = await h.commit((tx) => tx.conversation(fork.id), ctx).catch((e) => String(e));
console.log("record", JSON.stringify(rec));
await h.close(ctx);
